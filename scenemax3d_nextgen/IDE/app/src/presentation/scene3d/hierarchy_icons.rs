//! Original, type-specific outliner artwork; never dependent on font glyphs.
use bevy::prelude::*;

pub(super) fn drawing(kind: &str) -> impl Bundle {
    let (color, paths): ([u8; 3], Vec<Vec<(f32, f32)>>) = match kind {
        "SECTION" => (
            [243, 199, 101],
            vec![vec![
                (2., 7.),
                (2., 4.),
                (8., 4.),
                (10., 6.),
                (18., 6.),
                (18., 16.),
                (2., 16.),
                (2., 7.),
                (18., 7.),
            ]],
        ),
        "MODEL" => (
            [255, 184, 112],
            vec![
                vec![
                    (10., 2.),
                    (18., 6.),
                    (18., 14.),
                    (10., 18.),
                    (2., 14.),
                    (2., 6.),
                    (10., 2.),
                    (10., 10.),
                    (18., 6.),
                ],
                vec![(2., 6.), (10., 10.), (10., 18.)],
            ],
        ),
        "CAMERA" => (
            [204, 184, 255],
            vec![
                vec![(2., 6.), (12., 6.), (12., 15.), (2., 15.), (2., 6.)],
                vec![(12., 9.), (18., 6.), (18., 15.), (12., 12.)],
                vec![(4., 6.), (5., 3.), (9., 3.), (10., 6.)],
            ],
        ),
        "CODE" => (
            [139, 226, 180],
            vec![
                vec![(6., 5.), (2., 10.), (6., 15.)],
                vec![(14., 5.), (18., 10.), (14., 15.)],
                vec![(12., 3.), (8., 17.)],
            ],
        ),
        "LIGHT" => (
            [255, 221, 115],
            vec![
                vec![
                    (7., 14.),
                    (5., 11.),
                    (5., 7.),
                    (8., 4.),
                    (12., 4.),
                    (15., 7.),
                    (15., 11.),
                    (13., 14.),
                    (7., 14.),
                    (7., 17.),
                    (13., 17.),
                ],
                vec![(2., 5.), (1., 4.)],
                vec![(18., 5.), (19., 4.)],
                vec![(2., 10.), (0.5, 10.)],
                vec![(18., 10.), (19.5, 10.)],
            ],
        ),
        "CINEMATIC_RIG" | "CINEMATIC_TRACK" => (
            [211, 178, 255],
            vec![
                vec![(2., 3.), (18., 3.), (18., 17.), (2., 17.), (2., 3.)],
                vec![(2., 6.), (18., 6.)],
                vec![(2., 14.), (18., 14.)],
                vec![(8., 8.), (12., 10.), (8., 12.), (8., 8.)],
            ],
        ),
        "PATH" => (
            [106, 223, 210],
            vec![
                vec![(3., 16.), (5., 9.), (14., 11.), (17., 4.)],
                vec![(1., 14.), (5., 14.), (5., 18.), (1., 18.), (1., 14.)],
                vec![(15., 2.), (19., 2.), (19., 6.), (15., 6.), (15., 2.)],
            ],
        ),
        "SPHERE" => (
            [131, 210, 249],
            vec![circle(8., 8.), circle(3.5, 8.), vec![(2., 10.), (18., 10.)]],
        ),
        _ => (
            [131, 210, 249],
            vec![
                vec![(3., 3.), (17., 3.), (17., 17.), (3., 17.), (3., 3.)],
                vec![(3., 7.), (13., 7.), (13., 17.)],
                vec![(13., 7.), (17., 3.)],
            ],
        ),
    };
    scenemax_ide_ui::icons::styled_drawing(
        paths
            .into_iter()
            .map(|p| p.into_iter().map(|(x, y)| Vec2::new(x, y)).collect())
            .collect(),
        color,
        2.1,
    )
}

fn circle(x: f32, y: f32) -> Vec<(f32, f32)> {
    (0..=24)
        .map(|i| {
            let a = i as f32 * std::f32::consts::TAU / 24.;
            (10. + x * a.cos(), 10. + y * a.sin())
        })
        .collect()
}
