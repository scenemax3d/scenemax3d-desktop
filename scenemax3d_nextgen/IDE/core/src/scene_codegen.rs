//! Deterministic SceneMax source generation from scene designer documents.
use serde_json::Value;

fn text<'a>(v: &'a Value, key: &str, fallback: &'a str) -> &'a str {
    v[key].as_str().unwrap_or(fallback)
}
fn number(v: &Value, key: &str, fallback: f64) -> f64 {
    v[key].as_f64().unwrap_or(fallback)
}
fn flag(v: &Value, key: &str) -> bool {
    v[key].as_bool().unwrap_or(false)
}
fn quote(s: &str) -> String {
    format!("\"{}\"", s.replace('\\', "\\\\").replace('"', "\\\""))
}
fn vector<const N: usize>(v: &Value, fallback: [f64; N]) -> [f64; N] {
    std::array::from_fn(|i| v[i].as_f64().unwrap_or(fallback[i]))
}
fn tuple(v: &[f64]) -> String {
    format!(
        "({})",
        v.iter()
            .map(|n| format!("{}", if n.abs() < 1e-8 { 0. } else { *n }))
            .collect::<Vec<_>>()
            .join(",")
    )
}
fn angles(v: &Value, fallback: [f64; 4]) -> [f64; 3] {
    let [x, y, z, w] = vector(v, fallback);
    let unit = x * x + y * y + z * z + w * w;
    let test = x * y + z * w;
    let a = if test > 0.499 * unit {
        [0., 2. * x.atan2(w), std::f64::consts::FRAC_PI_2]
    } else if test < -0.499 * unit {
        [0., -2. * x.atan2(w), -std::f64::consts::FRAC_PI_2]
    } else {
        [
            (2. * x * w - 2. * y * z).atan2(-x * x + y * y - z * z + w * w),
            (2. * y * w - 2. * x * z).atan2(x * x - y * y - z * z + w * w),
            (2. * test / unit.max(1e-20)).clamp(-1., 1.).asin(),
        ]
    };
    a.map(f64::to_degrees)
}
fn color(s: &str) -> String {
    if s.starts_with('#') || s.contains(' ') {
        quote(s)
    } else {
        s.into()
    }
}
fn block(out: &mut String, code: &str) {
    if !code.is_empty() {
        out.push_str(code);
        if !code.ends_with('\n') {
            out.push('\n');
        }
    }
}

/// Generate all scene entities in hierarchy order, framed by the user's companion scripts.
/// Does not execute embedded source or mutate authoring documents.
pub fn generate(
    source: &str,
    filename: &str,
    init: &str,
    end: &str,
    native_materials: &[String],
) -> Result<String, String> {
    let root: Value = serde_json::from_str(source).map_err(|e| e.to_string())?;
    let mut entries = Vec::new();
    fn visit<'a>(v: &'a Value, depth: usize, result: &mut Vec<&'a Value>) -> Result<(), String> {
        if depth > 32 {
            return Err("Scene hierarchy exceeds 32 levels".into());
        }
        for e in v.as_array().ok_or("Expected scene entities array")? {
            if result.len() >= 2000 {
                return Err("Scene exceeds 2,000 entries".into());
            }
            result.push(e);
            if let Some(children) = e.get("children") {
                visit(children, depth + 1, result)?;
            }
        }
        Ok(())
    }
    visit(&root["entities"], 0, &mut entries)?;
    let mut out = format!(
        "// Auto-generated by SceneMax Designer from: {filename}\n// Do not edit manually - changes will be overwritten on save.\n\n"
    );
    block(&mut out, init);
    for (key, property) in [
        ("sceneEnvironmentShader", "environment.shader"),
        ("selectedBevySkybox", "skybox"),
    ] {
        let value = text(&root, key, "");
        if !value.is_empty() {
            out += &format!("Scene.{property} = {}\n", quote(value));
        }
    }
    let ambient = &root["bevyAmbientLight"];
    if flag(ambient, "enabled") {
        out += &format!(
            "{} => Lights.ambient : color {}, intensity {}, affectsLightmappedMeshes {}\n",
            text(ambient, "name", "scene_ambient"),
            color(text(ambient, "color", "#ffffff")),
            number(ambient, "brightness", 220.) / 220.,
            ambient["affectsLightmappedMeshes"]
                .as_bool()
                .unwrap_or(true)
        );
    }
    out += &format!(
        "camera.pos{}\ncamera.rotate{}\n\n",
        tuple(&vector(&root["gameCamera"]["position"], [0., 2., 10.])),
        tuple(&angles(&root["gameCamera"]["rotation"], [0., 1., 0., 0.]))
    );
    for e in &entries {
        let kind = text(e, "type", "");
        match kind {
            "CODE" => block(&mut out, text(e, "codeText", "")),
            "SECTION" | "CINEMATIC_RIG" | "CINEMATIC_TRACK" | "CAMERA" => {}
            "PATH" => block(&mut out, &path_code(e)?),
            "LIGHT" => block(&mut out, &light(e)),
            _ => block(&mut out, &entity(e, native_materials)?),
        }
    }
    for e in &entries {
        let kind = text(e, "type", "");
        let name = text(e, "name", "");
        let attach = text(e, "attachTo", "");
        if !attach.is_empty()
            && !matches!(
                kind,
                "SECTION"
                    | "CODE"
                    | "PATH"
                    | "CINEMATIC_RIG"
                    | "CINEMATIC_TRACK"
                    | "CAMERA"
                    | "LIGHT"
            )
        {
            out += &format!(
                "{name}.attach to {attach}: pos {}\n",
                tuple(&vector(&e["position"], [0.; 3]))
            );
        }
        if kind == "MODEL" && !text(e, "ikAsset", "").is_empty() {
            out += &format!("{name}.ik = {}\n", quote(text(e, "ikAsset", "")));
            if let Some(layers) = e["ikLayers"].as_array() {
                for layer in layers {
                    if !flag(layer, "enabled") {
                        continue;
                    }
                    let id = text(layer, "layerId", "");
                    if id.is_empty() {
                        continue;
                    }
                    for key in ["positionOffset", "rotationOffset", "polePosition"] {
                        if let Some(v) = layer.get(key) {
                            let a = v
                                .as_array()
                                .filter(|v| v.len() == 3)
                                .ok_or_else(|| format!("Invalid IK {key}"))?;
                            if a.iter().any(|n| {
                                n.as_f64().is_none_or(|n| !n.is_finite() || n.abs() > 1e10)
                            }) {
                                return Err(format!("Invalid IK {key}"));
                            }
                            out +=
                                &format!("{name}.ik.{id}.{key} = {}\n", tuple(&vector(v, [0.; 3])));
                        }
                    }
                    let target = text(layer, "target", "");
                    out += &format!(
                        "{name}.ik.{id}.play : {}blend {}, weight {}\n",
                        if target.is_empty() {
                            String::new()
                        } else {
                            format!("target {target}, ")
                        },
                        number(layer, "blend", 0.2),
                        number(layer, "weight", 1.)
                    );
                }
            }
        }
    }
    block(&mut out, end);
    Ok(out)
}

fn entity(e: &Value, native_materials: &[String]) -> Result<String, String> {
    let kind = text(e, "type", "");
    let name = text(e, "name", "Unnamed");
    let n = |k: &str, d: f64| number(e, k, d);
    let dims =
        |keys: &[(&str, f64)]| tuple(&keys.iter().map(|(k, d)| n(k, *d)).collect::<Vec<_>>());
    let (resource, mut attrs) = match kind {
        "MODEL" => (text(e, "resourcePath", "").to_owned(), vec![]),
        "BOX" => (
            "box".into(),
            vec![format!(
                "size {}",
                tuple(&[
                    n("sizeX", 0.5) * 2.,
                    n("sizeY", 0.5) * 2.,
                    n("sizeZ", 0.5) * 2.
                ])
            )],
        ),
        "SPHERE" => (
            "sphere".into(),
            vec![format!("radius {}", n("radius", 0.5))],
        ),
        "QUAD" => (
            "quad".into(),
            vec![format!(
                "size {}",
                dims(&[("quadWidth", 1.), ("quadHeight", 1.)])
            )],
        ),
        "WEDGE" => (
            "wedge".into(),
            vec![format!(
                "size {}",
                dims(&[("wedgeWidth", 1.), ("wedgeHeight", 1.), ("wedgeDepth", 1.)])
            )],
        ),
        "CYLINDER" | "CONE" | "HOLLOW_CYLINDER" => {
            let mut attrs = vec![
                format!(
                    "radius {}",
                    dims(&[("radiusTop", 0.5), ("radiusBottom", 0.5)])
                ),
                format!("height {}", n("height", 1.)),
            ];
            if kind == "HOLLOW_CYLINDER" {
                attrs.push(format!(
                    "inner radius {}",
                    dims(&[("innerRadiusTop", 0.25), ("innerRadiusBottom", 0.25)])
                ));
            }
            (kind.to_lowercase().replace('_', " "), attrs)
        }
        "STAIRS" => (
            "stairs".into(),
            vec![
                format!(
                    "size {}",
                    dims(&[
                        ("stairsWidth", 2.),
                        ("stairsStepHeight", 0.3),
                        ("stairsStepDepth", 0.5)
                    ])
                ),
                format!("steps {}", n("stairsStepCount", 5.)),
            ],
        ),
        "ARCH" => (
            "arch".into(),
            vec![
                format!(
                    "size {}",
                    dims(&[("archWidth", 3.), ("archHeight", 3.), ("archDepth", 1.)])
                ),
                format!("thickness {}", n("archThickness", 0.5)),
                format!("segments {}", n("archSegments", 12.)),
            ],
        ),
        _ => {
            return Err(format!(
                "Cannot generate unsupported scene entity type {kind:?} ({name})"
            ));
        }
    };
    if resource.is_empty() {
        return Err(format!("Missing model resource for {name}"));
    }
    let mut prefix = String::new();
    if flag(
        e,
        if kind == "MODEL" {
            "staticModel"
        } else {
            "staticEntity"
        },
    ) {
        prefix += "static ";
    } else if kind == "MODEL" && flag(e, "dynamicModel") {
        prefix += "dynamic ";
    }
    if kind != "MODEL" && flag(e, "colliderEntity") {
        prefix += "collider ";
    }
    if flag(e, "hidden") {
        attrs.push("hidden".into());
    }
    if flag(e, "multiplayer") {
        attrs.push("multiplayer".into());
    }
    attrs.push(format!("pos {}", tuple(&vector(&e["position"], [0.; 3]))));
    let scale = vector(&e["scale"], [1.; 3]);
    // Explicit unit scale must override the model catalog default, just like the designer.
    if scale != [1.; 3] || (kind == "MODEL" && e["scale"].is_array()) {
        attrs.push(format!(
            "scale {}",
            if scale[0] == scale[1] && scale[1] == scale[2] {
                scale[0].to_string()
            } else {
                tuple(&scale)
            }
        ));
    }
    let rotate = angles(&e["rotation"], [0., 0., 0., 1.]);
    if rotate.iter().any(|v| v.abs() > 0.0001) {
        attrs.push(format!("rotate{}", tuple(&rotate)));
    }
    match text(e, "shadowMode", "none") {
        "cast" => attrs.push("shadow mode cast".into()),
        "receive" => attrs.push("shadow mode receive".into()),
        "both" => attrs.push("shadow mode on".into()),
        _ => {}
    }
    if kind == "MODEL" {
        let shape = text(e, "modelCollisionShape", "default");
        if matches!(shape, "box" | "boxes" | "mesh" | "none") {
            attrs.push(format!("collision shape {shape}"));
        }
        let joints = text(e, "jointMapping", "")
            .split(',')
            .map(str::trim)
            .filter(|s| !s.is_empty())
            .map(quote)
            .collect::<Vec<_>>();
        if !joints.is_empty() {
            attrs.push(format!("joints ({})", joints.join(",")));
        }
    }
    let material = text(e, "material", "");
    let native = kind == "MODEL" || native_materials.iter().any(|name| name == material);
    if !material.is_empty() && !native {
        attrs.push(format!("material {}", quote(material)));
    }
    let vehicle = if kind == "MODEL" && flag(e, "vehicleModel") {
        " vehicle"
    } else {
        ""
    };
    let mut out = format!(
        "{name} => {prefix}{resource}{vehicle} : {}{}\n",
        attrs.join(", "),
        if kind == "MODEL" { " async" } else { "" }
    );
    for property in ["material", "shader"] {
        if property == "material" && !native {
            continue;
        }
        let value = text(e, property, "");
        if !value.is_empty() {
            out += &format!("{name}.{property} = {}\n", quote(value));
        }
    }
    Ok(out)
}

fn light(e: &Value) -> String {
    let kind = text(e, "lightType", "point")
        .to_lowercase()
        .replace(' ', "_");
    let mut attrs = Vec::new();
    if kind == "sky" {
        let preset = text(e, "lightPreset", "");
        if !preset.is_empty() {
            attrs.push(format!("preset {}", quote(preset)));
        }
        attrs.push(format!("exposure {}", number(e, "lightExposure", 1.)));
        attrs.push(format!(
            "ambient {}",
            color(text(e, "lightAmbientColor", "#ffffff"))
        ));
    } else {
        if matches!(kind.as_str(), "point" | "spot" | "probe") {
            attrs.push(format!("pos {}", tuple(&vector(&e["position"], [0.; 3]))));
        }
        attrs.push(format!("color {}", color(text(e, "lightColor", "warm"))));
        attrs.push(format!(
            "intensity {} {}",
            number(e, "lightIntensity", 1.),
            text(e, "lightIntensityUnit", "")
        ));
        if matches!(kind.as_str(), "point" | "spot" | "probe") {
            attrs.push(format!("range {}", number(e, "lightRange", 20.)));
        }
        if kind == "spot" && !text(e, "lightLookAtTarget", "").is_empty() {
            attrs.push(format!("look at {}", text(e, "lightLookAtTarget", "")));
        } else if matches!(kind.as_str(), "spot" | "directional") {
            let v = vector(&e["lightDirection"], [0., -1., 0.]);
            let [x, y, z, w] = vector(&e["rotation"], [0., 0., 0., 1.]);
            let q = [x, y, z];
            let cross = |a: [f64; 3], b: [f64; 3]| {
                [
                    a[1] * b[2] - a[2] * b[1],
                    a[2] * b[0] - a[0] * b[2],
                    a[0] * b[1] - a[1] * b[0],
                ]
            };
            let t = cross(q, v).map(|n| 2. * n);
            let c = cross(q, t);
            let d: [f64; 3] = std::array::from_fn(|i| v[i] + w * t[i] + c[i]);
            let len = d.iter().map(|n| n * n).sum::<f64>().sqrt().max(1e-20);
            attrs.push(format!("direction {}", tuple(&d.map(|n| n / len))));
        }
        if kind == "spot" {
            attrs.push(format!("angle {}", number(e, "lightAngle", 45.)));
        }
        let shadow = text(e, "lightShadowMode", "off");
        if !matches!(shadow, "off" | "none" | "") {
            attrs.push(format!("shadow {shadow}"));
        }
    }
    format!(
        "{} => Lights.{kind} : {}\n",
        text(e, "name", "light"),
        attrs.join(", ")
    )
}

fn path_code(e: &Value) -> Result<String, String> {
    let data = &e["pathData"];
    let Some(points) = data["controlPoints"].as_array().filter(|p| p.len() >= 2) else {
        return Ok(String::new());
    };
    let steps = data["subdivisions"].as_u64().unwrap_or(20) as usize;
    if steps == 0 || steps > 4096 || points.len() * steps > 100000 {
        return Err("Path sampling exceeds supported bounds".into());
    }
    let segments = if flag(data, "closed") {
        points.len()
    } else {
        points.len() - 1
    };
    let mut values = Vec::new();
    for i in 0..segments {
        let a = &points[i];
        let b = &points[(i + 1) % points.len()];
        let p = vector(&a["position"], [0.; 3]);
        let q = vector(&b["position"], [0.; 3]);
        let tin = vector(&b["tangentIn"], [0.; 3]);
        let tout = vector(&a["tangentOut"], [0.; 3]);
        let h: [f64; 3] = std::array::from_fn(|j| p[j] + tout[j]);
        let k: [f64; 3] = std::array::from_fn(|j| q[j] + tin[j]);
        let direction = |t: f64| {
            let u = 1. - t;
            let d: [f64; 3] = std::array::from_fn(|j| {
                3. * u * u * (h[j] - p[j]) + 6. * u * t * (k[j] - h[j]) + 3. * t * t * (q[j] - k[j])
            });
            [
                -d[1].atan2((d[0] * d[0] + d[2] * d[2]).sqrt()).to_degrees(),
                d[0].atan2(d[2]).to_degrees(),
                0.,
            ]
        };
        for s in 0..(steps + usize::from(i == segments - 1)) {
            let t = s as f64 / steps as f64;
            let u = 1. - t;
            let pos: [f64; 3] = std::array::from_fn(|j| {
                p[j] * u * u * u + 3. * h[j] * u * u * t + 3. * k[j] * u * t * t + q[j] * t * t * t
            });
            let rot = if a["rotationOverride"].is_array() || b["rotationOverride"].is_array() {
                let start = vector(&a["rotationOverride"], direction(0.));
                let end = vector(&b["rotationOverride"], direction(1.));
                std::array::from_fn(|j| start[j] + (end[j] - start[j]) * t)
            } else {
                direction(t)
            };
            values.extend(
                pos.into_iter()
                    .chain(rot)
                    .map(|n| format!("{}", (n * 1000.).round() / 1000.)),
            );
        }
    }
    Ok(format!(
        "var {} = [{}]\n",
        text(e, "name", "path"),
        values.join(",")
    ))
}

#[cfg(test)]
mod ik_pose_tests {
    use super::*;
    #[test]
    fn generated_ik_pose_precedes_play_and_retains_negative_values() {
        let scene = r#"{"entities":[{"type":"MODEL","name":"subject","resourcePath":"rig","ikAsset":"contacts","ikLayers":[{"layerId":"foot","enabled":true,"target":"anchor","positionOffset":[1,-2,3],"rotationOffset":[0,45,-10],"polePosition":[0,1,-1]}]}]}"#;
        let code = generate(scene, "scene", "", "", &[]).unwrap();
        for key in ["positionOffset", "rotationOffset", "polePosition"] {
            assert!(
                code.find(&format!("subject.ik.foot.{key} =")).unwrap()
                    < code.find("subject.ik.foot.play").unwrap(),
                "{code}"
            );
        }
        assert!(generate(&scene.replace("[1,-2,3]", "[1,2]"), "scene", "", "", &[]).is_err());
    }
}

#[cfg(test)]
mod scale_tests {
    use super::*;
    #[test]
    fn authored_model_scale_overrides_catalog_even_when_it_is_one() {
        for (scale, expected) in [("[1,1,1]", "scale 1"), ("[2,3,4]", "scale (2,3,4)")] {
            let source = format!(r#"{{"entities":[{{"type":"MODEL","name":"subject","resourcePath":"sample","scale":{scale}}}]}}"#);
            let code = generate(&source, "scene.smdesign", "", "", &[]).unwrap();
            assert!(code.contains(expected), "{code}");
        }
        let code = generate(r#"{"entities":[{"type":"MODEL","name":"subject","resourcePath":"sample"}]}"#, "scene.smdesign", "", "", &[]).unwrap();
        assert!(!code.contains("scale "));
    }
}
